"""ChatService coordinates memory, retrieval, prompt construction, and LLM streaming."""

import logging
from typing import Iterator

from chatbot.errors import InvalidInputError
from chatbot.llm_client import BaseLLM
from chatbot.memory import ConversationMemory
from chatbot.models import ChatSession
from chatbot.prompts import PromptBuilder, clean_user_input
from chatbot.retriever import BaseRetriever

logger = logging.getLogger(__name__)


class ChatService:
    """Core application service connecting UI interactions to the LLM backend."""

    def __init__(
        self,
        llm: BaseLLM,
        memory: ConversationMemory,
        prompt_builder: PromptBuilder,
        retriever: BaseRetriever,
        sessions_dir: str | None = None,
    ) -> None:
        self.llm = llm
        self.memory = memory
        self.prompt_builder = prompt_builder
        self.retriever = retriever
        self.sessions_dir = sessions_dir

    def send_message(self, session: ChatSession, user_input: str) -> Iterator[str]:
        """Process a user message and stream the model's response.

        Steps in exact sequence:
        1. Clean/validate input (raises InvalidInputError on failure).
        2. Retrieve conversation context from memory (prior to adding the new message).
        3. Query the retriever for relevant context documents.
        4. Build the structured message prompt list.
        5. Add the user message to the session history.
        6. Stream from the LLM, yielding chunks and accumulating output text.
        7. On successful stream completion, store the assistant message in the session.
        8. On failure:
           - If partial text was received, save it as an assistant message with incomplete=True.
           - If zero chunks were received, pop the newly added user message to keep history clean.
           - Re-raise the exception.

        Args:
            session: The active conversation session.
            user_input: Raw input string from the user.

        Yields:
            Token strings generated by the LLM.
        """
        # 1. Clean/validate input
        max_chars = getattr(self.prompt_builder, "max_input_chars", 4000)
        cleaned_input = clean_user_input(user_input, max_chars=max_chars)

        # 2. Get history context from memory (before adding new message)
        history_context = self.memory.get_context(session)

        # 3. Call retriever
        docs = self.retriever.retrieve(cleaned_input)
        if docs:
            retrieved_context = "\n\n".join(
                f"[Source: {doc.source}]\n{doc.content}" if doc.source else doc.content
                for doc in docs
            )
        else:
            retrieved_context = None

        # 4. Build prompt
        messages = self.prompt_builder.build(
            history_messages=history_context,
            user_input=cleaned_input,
            retrieved_context=retrieved_context,
        )

        # 5. Add user message to session
        session.add(role="user", content=cleaned_input)

        # 6. Stream from LLM, yield chunks, accumulate text
        accumulated_chunks: list[str] = []
        try:
            for chunk in self.llm.stream(messages):
                accumulated_chunks.append(chunk)
                yield chunk
        except Exception as exc:
            # 8. Mid-stream failure handling
            if accumulated_chunks:
                full_text = "".join(accumulated_chunks)
                session.add(role="assistant", content=full_text, incomplete=True)
                if self.sessions_dir:
                    try:
                        session.save(self.sessions_dir)
                    except Exception as exc2:
                        logger.warning("Failed to persist session: %s", exc2)
            else:
                if session.messages and session.messages[-1].role == "user":
                    session.messages.pop()
            raise exc
        else:
            # 7. Successful completion
            full_text = "".join(accumulated_chunks)
            session.add(role="assistant", content=full_text, incomplete=False)
            if self.sessions_dir:
                try:
                    session.save(self.sessions_dir)
                except Exception as exc:
                    logger.warning("Failed to persist session: %s", exc)

    def regenerate(self, session: ChatSession) -> Iterator[str]:
        """Regenerate the last assistant response.

        Removes the last assistant message (if present), removes the preceding user message,
        and re-sends that user message through the conversation pipeline.

        Args:
            session: The active conversation session.

        Returns:
            Stream generator for the new completion.

        Raises:
            InvalidInputError: If there is no preceding user message to regenerate.
        """
        if session.messages and session.messages[-1].role == "assistant":
            session.messages.pop()

        if not session.messages or session.messages[-1].role != "user":
            raise InvalidInputError("No user message found to regenerate.")

        last_user_message = session.messages.pop()
        return self.send_message(session, last_user_message.content)
